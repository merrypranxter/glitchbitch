export const MAX_PALETTE_STOPS=12;
export const isValidHexColor=v=>typeof v==='string'&&/^#[0-9a-f]{6}$/i.test(v);
export function normalizeColorStops(colors,fallback=PALETTES['ACID ORCHID']){
 return Array.isArray(colors)&&colors.length>=2&&colors.length<=MAX_PALETTE_STOPS&&
  colors.every(isValidHexColor)?colors.map(c=>c.toLowerCase()):[...fallback];
}
export function randomRgbColor(random=Math.random){
 const channel=()=>Math.max(0,Math.min(255,Math.floor(random()*256)));
 return '#'+[channel(),channel(),channel()].map(n=>n.toString(16).padStart(2,'0')).join('');
}
export function shuffleColorStops(colors,random=Math.random){
 const a=colors.slice();
 for(let i=a.length-1;i>0;i--){
  const j=Math.max(0,Math.min(i,Math.floor(random()*(i+1))));
  [a[i],a[j]]=[a[j],a[i]];
 }
 if(a.length>1&&a.every((c,i)=>c===colors[i]))a.push(a.shift());
 return a;
}
