const byId = new Map(retroFonts.map(font=>[font.id,font]));
export function getRetroFont(id) { return byId.get(id) || retroFonts[0]; }
export function quoteFontCSS(id,px) {
  const font=getRetroFont(id);
  return font.weight + " " + Math.max(8,Math.round(px)) + "px " + font.family;
}
const inFlight=new Map(), loaded=new Set();
let revision=0;
export function retroFontRevision(){ return revision; }
export function retroFontReady(id){
  const font=getRetroFont(id);
  return !font.bundle || loaded.has(font.bundle);
}
export function ensureRetroFontLoaded(id){
  const font=getRetroFont(id);
  if(!font.bundle || typeof document==="undefined" || !document.fonts?.load)
    return Promise.resolve(true);
  const key=font.bundle;
  if(loaded.has(key))return Promise.resolve(true);
  if(inFlight.has(key))return inFlight.get(key);
  const family=retroFontNames[key];
  const bundled=retroFonts.find(f=>f.id===key);
  const descriptor=bundled.weight+' 42px "'+family+'"';
  const task=document.fonts.load(descriptor).then(faces=>{
    if(!faces?.length)throw Error("Typeface not available: "+font.label);
    loaded.add(key);
    revision++;
    return true;
  }).catch(err=>{inFlight.delete(key);throw err;});
  inFlight.set(key,task);
  return task;
}
